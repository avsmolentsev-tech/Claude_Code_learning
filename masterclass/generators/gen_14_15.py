ITEMS=[('Корпус НТ-50','Мехобработка',1.8),('Вал привода','Мехобработка',0.9),('Кронштейн','Мехобработка',0.35),
 ('Рама сборочная','Сварка',2.4),('Патрубок DN100','Сварка',0.6),('Крышка ТО-40','Покраска',0.45),
 ('Корпус окрашенный','Покраска',0.8),('Насосный агрегат','Сборка',3.6),('Узел привода','Сборка',1.5)]
