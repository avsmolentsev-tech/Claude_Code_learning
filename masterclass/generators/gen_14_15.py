O='site/cases/14-production'; os.makedirs(f'{O}/transcripts',exist_ok=True)
# Настоящая причина срывов — узкое место на участке «Мехобработка» (станок ЧПУ-3),
# но в планёрках её маскируют формулировками «не привезли материал», «сменили приоритет».
LINES=['Мехобработка','Сварка','Покраска','Сборка','Упаковка']
BOTTLENECK='Мехобработка'
CAUSES=['Ожидание материала','Смена приоритета заказа','Простой оборудования','Нет решения по чертежу',
        'Перегруз участка','Задержка предыдущего этапа','Отсутствие оператора']
rows=[]; start=dt.date(2026,7,1)
for i in range(180):
    order=f'ПЗ-{2400+i}'
    line=random.choices(LINES,weights=[0.30,0.20,0.15,0.22,0.13])[0]
    plan_start=start+dt.timedelta(days=random.randint(0,70))
    plan_dur=random.randint(2,9)
    plan_end=plan_start+dt.timedelta(days=plan_dur)
    # узкое место: на мехобработке задержки и чаще, и длиннее
    if line==BOTTLENECK:
        delay=random.choices([0,1,2,3,5,8,12],weights=[18,14,16,16,16,12,8])[0]
        cause=random.choices(CAUSES,weights=[22,18,26,8,14,8,4])[0]   # простой оборудования доминирует
    else:
        delay=random.choices([0,1,2,3,5],weights=[46,22,16,10,6])[0]
        cause=random.choices(CAUSES,weights=[14,14,8,10,10,38,6])[0]  # чаще «задержка предыдущего этапа»
    fact_end=plan_end+dt.timedelta(days=delay)
    rows.append({'Заказ':order,'Участок':line,'Изделие':random.choice(['Корпус НТ-50','Вал привода','Рама сборочная','Крышка ТО-40','Кронштейн','Патрубок DN100']),
      'Плановый старт':plan_start.isoformat(),'Плановое окончание':plan_end.isoformat(),
      'Фактическое окончание':fact_end.isoformat(),'Отклонение, дней':delay,
      'Причина отклонения':(cause if delay>0 else ''),
      'Оборудование':random.choice(['ЧПУ-1','ЧПУ-2','ЧПУ-3','Сварочный пост А','Сварочный пост Б','Камера покраски','Стенд сборки']) if line in (BOTTLENECK,'Сварка','Покраска','Сборка') else '',
      'Смена':random.choice(['1','2'])})
by_line=collections.defaultdict(list)
for r in rows: by_line[r['Участок']].append(r['Отклонение, дней'])
avg={l:sum(v)/len(v) for l,v in by_line.items()}
worst=max(avg,key=avg.get)
assert worst==BOTTLENECK, f'узкое место должно быть на {BOTTLENECK}, получилось {worst}'
assert avg[BOTTLENECK] > sorted(avg.values())[-2]*1.4, 'узкое место должно выделяться явно'
with open(f'{O}/demo_production_plan_fact.csv','w',newline='',encoding='utf-8-sig') as f:
    w=csv.DictWriter(f,fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)

