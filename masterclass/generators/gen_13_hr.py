profiles=[]
for i in range(30):
    name=f'{random.choice(LAST)} {random.choice(FIRST)}{random.choice(FIRST)}'
    years=random.choice([1,2,3,4,5,6,7,8,10,12,15])
    core=random.sample(SKILL_CORE, k=random.randint(2,7))
    extra=random.sample(SKILL_EXTRA, k=random.randint(1,5))
    lead = years>=6 and random.random()<0.45
    city=random.choice(CITY)
    fit = len([s for s in core if s in ('подбор насосного оборудования','гидравлический расчёт','тепловой расчёт','подготовка технических решений')])
    profiles.append(dict(name=name,years=years,core=core,extra=extra,lead=lead,city=city,fit=fit))
    jobs=[]
    y=2026
    for j in range(min(3, max(1, years//3))):
        dur=random.randint(1,5); y0=y-dur
        jobs.append(f"{y0}–{y if j==0 else y}: {random.choice(COMPANY)}, {'руководитель группы' if (lead and j==0) else random.choice(['инженер-конструктор','инженер по подбору оборудования','ведущий инженер','технический специалист'])}\n"
                    f"  Задачи: {', '.join(random.sample(core+extra, k=min(4,len(core+extra))))}.")
        y=y0
    txt=f"""РЕЗЮМЕ
{name}
Город: {city}
Желаемая должность: инженер по подбору оборудования
Опыт работы: {years} лет
Образование: {random.choice(['СПбПУ Петра Великого, теплоэнергетика','СПбГАСУ, инженерные системы','УрФУ, энергомашиностроение','КНИТУ, машиностроение','НГТУ, теплотехника'])}, {2026-years-random.randint(0,3)}

ОПЫТ РАБОТЫ
{chr(10).join(jobs)}

КЛЮЧЕВЫЕ НАВЫКИ
{chr(10).join('- '+s for s in core+extra)}

ДОПОЛНИТЕЛЬНО
Готовность к командировкам: {random.choice(['да','да','ограниченно','нет'])}
Формат работы: {random.choice(['офис','офис','гибрид','удалённо'])}
Ожидания по доходу: {random.choice([90,110,120,130,140,150,160,180,200])} 000 ₽
"""
    open(f'{O}/resumes/resume_{i+1:02d}_{name.split()[0]}.txt','w',encoding='utf-8').write(txt)

