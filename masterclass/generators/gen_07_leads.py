# -*- coding: utf-8 -*-
"""Кейс 07 «AI Lead Intelligence»: demo_crm_leads (>=100 компаний) + офлайн-профили.
Паттерны: горячие/старые/крупные/малые/неподходящие/действующие клиенты."""
import csv, random, datetime as dt, os, collections, json
random.seed(70726)
OUT='site/cases/07-leads'; os.makedirs(OUT, exist_ok=True)
TODAY = dt.date(2026, 9, 13)

INDUSTRY = ['Пищевое производство','Металлообработка','ЖКХ и теплоснабжение','Нефтегаз','Химия',
            '农 Агропром'.replace('农 ',''),'Строительство','Логистика','Фармацевтика','Энергетика']
SOURCE   = ['Сайт — заявка','Выставка','Холодный обзвон','Рекомендация','Тендерная площадка','Реклама','Входящий звонок']
STAGE    = ['Новый','Квалификация','Отправлено КП','Переговоры','Счёт выставлен','Пауза','Закрыт — отказ']
MGR      = ['Астахов И.','Белова М.','Гурьев П.','Дорохина Е.','Ким А.']
CITY     = ['Москва','Санкт-Петербург','Казань','Екатеринбург','Новосибирск','Самара','Ростов-на-Дону','Пермь','Уфа','Тюмень']

BASE = ['Волгаэнерго','Севергаз','ТеплоСеть','Сибнефтемаш','Промальянс','Ремстрой','Энергопоток','ТехноЛайн',
 'Гидромаш','Аквасервис','Промкомплект','СтройИнвест','Северный ветер','Химпром','Агроресурс','Мехзавод',
 'ТеплоДом','Уралснаб','Волга-Трейд','Энергомонтаж','Метизный двор','Криоген','Полимер-НН','Вектор-Строй',
 'ГазДеталь','НефтеХимСервис','АгроТехника','МолокоПлюс','ХлебЗавод','Мясокомбинат','Стеклотара','ЛесПром',
 'БумагаСтандарт','ТрубоСталь','Литейщик','КотлоМаш','ВодоканалСервис','ТеплоЭнергоРемонт','ЭкоСфера','БиоТех']
SUFF = ['ООО','АО','ПАО','ГК','ЗАО']

rows=[]
def mk(i):
    name=f'{random.choice(SUFF)} «{random.choice(BASE)}-{random.choice(["", "Н","Юг","Плюс","Групп","Сервис","Про"])}»'.replace('-»','»')
    return name

kinds = (['горячий']*18 + ['старый']*22 + ['крупный']*14 + ['малый']*20 +
         ['неподходящий']*14 + ['действующий клиент']*14)
random.shuffle(kinds)

for i, kind in enumerate(kinds, 1):
    name = mk(i)
    ind  = random.choice(INDUSTRY)
    if kind=='горячий':
        days=random.randint(1,6);  stage=random.choice(['Отправлено КП','Переговоры','Счёт выставлен']); amount=random.randint(400,2500)*1000
    elif kind=='старый':
        days=random.randint(95,260); stage=random.choice(['Пауза','Квалификация','Отправлено КП']); amount=random.randint(150,900)*1000
    elif kind=='крупный':
        days=random.randint(7,40);  stage=random.choice(['Квалификация','Переговоры','Отправлено КП']); amount=random.randint(3000,15000)*1000
    elif kind=='малый':
        days=random.randint(3,60);  stage=random.choice(['Новый','Квалификация']); amount=random.randint(30,180)*1000
    elif kind=='неподходящий':
        days=random.randint(10,120); stage=random.choice(['Новый','Закрыт — отказ']); amount=random.randint(10,90)*1000
        ind = random.choice(['Розничная торговля','Частное лицо','Реклама и маркетинг','Образование'])
    else:
        days=random.randint(14,90); stage=random.choice(['Переговоры','Счёт выставлен','Пауза']); amount=random.randint(500,4000)*1000
    last = (TODAY - dt.timedelta(days=days)).isoformat()
    created = (TODAY - dt.timedelta(days=days+random.randint(5,200))).isoformat()
    comments = {
     'горячий':['Просил счёт до конца недели','Согласовывает бюджет, ждёт КП','Сравнивает с конкурентом, решение в этом месяце'],
     'старый':['Перенесли на следующий год','Не отвечает на письма','Был интерес, потом тишина'],
     'крупный':['Тендер на 4 квартал, нужен расчёт','Запросили техспецификацию','Головной офис согласовывает поставщика'],
     'малый':['Разовая закупка, спрашивал цену','Нужна одна позиция','Уточнял наличие на складе'],
     'неподходящий':['Не наш профиль','Искали розницу','Просили то, что мы не производим'],
     'действующий клиент':['Действующий договор, обсуждаем расширение','Повторная закупка','Плановое ТО в ноябре'],
    }
    rows.append({'Компания':name,'Сайт':f'{name.split("«")[1].split("»")[0].lower().replace(" ","-")}.ru',
      'Отрасль':ind,'Город':random.choice(CITY),'Контакт':random.choice(['Иванов А.','Петрова С.','Сидоров К.','Мельник О.','Гусев Д.','Рахимова Л.']),
      'Должность':random.choice(['Главный инженер','Директор по закупкам','Технический директор','Снабженец','Генеральный директор']),
      'Источник':random.choice(SOURCE),'Дата создания':created,'Менеджер':random.choice(MGR),'Стадия':stage,
      'Сумма сделки, ₽':amount,'Последнее касание':last,'Дней без касания':days,
      'Комментарий менеджера':random.choice(comments[kind]),'Тип (учебная метка)':kind})

random.shuffle(rows)
c = collections.Counter(r['Тип (учебная метка)'] for r in rows)
assert len(rows) >= 100, 'ТЗ требует минимум 100 компаний'
assert len(c) == 6, 'должны быть все шесть типов лидов'
hot = [r for r in rows if r['Тип (учебная метка)']=='горячий']
assert all(r['Дней без касания'] <= 7 for r in hot), 'горячие должны быть со свежим касанием'
old = [r for r in rows if r['Тип (учебная метка)']=='старый']
assert all(r['Дней без касания'] >= 90 for r in old), 'старые должны быть давно без касания'
big = [r for r in rows if r['Тип (учебная метка)']=='крупный']
assert min(r['Сумма сделки, ₽'] for r in big) >= 3_000_000, 'крупные — от 3 млн'

cols=list(rows[0].keys())
with open(f'{OUT}/demo_crm_leads.csv','w',newline='',encoding='utf-8-sig') as f:
    w=csv.DictWriter(f,fieldnames=cols); w.writeheader(); w.writerows(rows)
from openpyxl import Workbook
from openpyxl.styles import Font
wb=Workbook(); ws=wb.active; ws.title='Лиды'; ws.append(cols)
for cc in ws[1]: cc.font=Font(bold=True)
for r in rows: ws.append([r[k] for k in cols])
ws.freeze_panes='A2'
for i,k in enumerate(cols,1): ws.column_dimensions[ws.cell(1,i).column_letter].width=max(12,min(26,len(k)+4))
wb.save(f'{OUT}/demo_crm_leads.xlsx')

# офлайн-профили 18 компаний (чтобы практика шла без интернета)
prof=[]
for r in rows[:18]:
    prof.append({'Компания':r['Компания'],'Сайт':r['Сайт'],'Отрасль':r['Отрасль'],'Город':r['Город'],
      'Год основания':random.randint(1994,2019),'Сотрудников':random.choice([28,45,70,120,240,380,600,1100]),
      'Выручка, млн ₽/год':random.choice([90,140,260,410,780,1200,2400]),
      'Что производит/делает':'Профиль для офлайн-режима: используйте как «результат веб-исследования», если интернет недоступен.',
      'Публичные сигналы':random.choice(['Объявили о расширении производства','Выиграли крупный тендер',
        'Сменился директор по закупкам','Открыли новую площадку','Сообщали о модернизации оборудования','Публичных новостей не найдено'])})
with open(f'{OUT}/offline_company_profiles.json','w',encoding='utf-8') as f:
    json.dump(prof,f,ensure_ascii=False,indent=1)

print(f'лидов: {len(rows)}; состав: {dict(c)}')
print(f'офлайн-профилей: {len(prof)}')
print(f'записано: {OUT}/demo_crm_leads.csv/.xlsx + offline_company_profiles.json')
