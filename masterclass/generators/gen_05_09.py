def docx(path, title, blocks):
    d=Document(); d.add_heading(title,0)
    for kind,text in blocks:
        if kind=='h': d.add_heading(text,level=1)
        elif kind=='p': d.add_paragraph(text)
        elif kind=='b': d.add_paragraph(text, style='List Bullet')
    d.save(path)

